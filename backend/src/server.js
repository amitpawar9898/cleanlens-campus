const express = require('express'), helmet = require('helmet'), cors = require('cors'), morgan = require('morgan'), rate = require('express-rate-limit'), path = require('path');
const cfg = require('./config'), { pool } = require('./db'), err = require('./middleware/error'), ai = require('./services/ai');
const app = express();
app.set('trust proxy', 1);
app.use(helmet({ crossOriginResourcePolicy: { policy: 'cross-origin' }, contentSecurityPolicy: false }));
app.use(cors({ origin: cfg.corsOrigin === '*' ? true : cfg.corsOrigin.split(',') }));
app.use(express.json({ limit: '1mb' }));
if (!cfg.prod) app.use(morgan('dev'));
app.use(rate({ windowMs: 60000, limit: 300, standardHeaders: true, legacyHeaders: false }));
const strict = rate({ windowMs: 60000, limit: 20, message: { error: 'Too many attempts, slow down.' } });
const sensitive = (limit, windowMs=60000) => rate({windowMs,limit,standardHeaders:true,legacyHeaders:false,message:{error:'Too many requests. Please try again later.'}});
const files = require('./services/files');
app.get('/files/:name', (req, res) => { let ok = false; try { ok = files.verify(req.params.name, req.query.exp, req.query.sig); } catch {} if (!ok) return res.status(403).json({ error: 'Link expired or invalid' }); res.set('Cache-Control', 'private, max-age=300'); res.sendFile(path.resolve(cfg.uploadDir, req.params.name)); });
app.get('/api/health', async (req, res) => { try { await pool.query('SELECT 1'); res.json({ ok: true, ai: ai.status().configured, ai_provider: ai.status().provider, registration_enabled:cfg.publicRegistration, time: new Date() }); } catch { res.status(503).json({ ok: false }); } });
app.use('/api/auth', strict, require('./routes/auth'));
app.use('/api/users', sensitive(90), require('./routes/users'));
app.use('/api/locations', sensitive(90), require('./routes/locations'));
app.use('/api/complaints', sensitive(30), require('./routes/complaints'));
app.use('/api/tasks', sensitive(45), require('./routes/tasks'));
app.use('/api/inspections', sensitive(20), require('./routes/inspections'));
app.use('/api/ai', rate({ windowMs: 60000, limit: 15 }), require('./routes/ai'));
app.use('/api/notifications', sensitive(90), require('./routes/notifications'));
app.use('/api/analytics', sensitive(90), require('./routes/analytics'));
app.use('/api/admin', sensitive(45), require('./routes/admin'));
app.use('/api', (req, res) => res.status(404).json({ error: 'Route not found' }));
app.use(express.static(path.join(__dirname, '../public'), { setHeaders: (res, f) => { if (f.endsWith('sw.js')) res.set({ 'Cache-Control': 'no-cache', 'Service-Worker-Allowed': '/' }); } }));
app.use(err);
if (require.main === module) app.listen(cfg.port, () => {
  console.log(`CleanLens API on http://localhost:${cfg.port}  (AI ${ai.status().configured ? ai.status().provider : 'off'})`);
  require('./services/deadlines').start();
});
module.exports = app;
